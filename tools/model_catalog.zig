};

fn writeEnumSet(writer: *std.Io.Writer, name: []const u8, values: anytype) !void {
    try writer.print("            .{s} = model.ModelProfile.", .{name});
    const set_name = if (std.mem.eql(u8, name, "reasoning_efforts"))
        "ReasoningEffortSet"
    else if (std.mem.eql(u8, name, "service_tiers"))
        "ServiceTierSet"
    else if (std.mem.eql(u8, name, "builtin_tools"))
        "BuiltinToolSet"
    else
        "ContentTypeSet";
    try writer.print("{s}.initMany(&.{{", .{set_name});
    if (values.len > 1) try writer.writeByte(' ');
    for (values, 0..) |value, index| {
        if (index > 0) try writer.writeAll(", ");
        try writer.print(".{s}", .{@tagName(value)});
    }
    if (values.len > 1) try writer.writeByte(' ');
    try writer.writeAll("}),\n");
}

fn writeOptionalInteger(writer: *std.Io.Writer, value: ?u64) !void {
    if (value) |integer| try writer.print("{}", .{integer}) else try writer.writeAll("null");
}

test "generator is deterministic and validates source ordering" {
    const fixture =
        \\{"version":1,"updated_at":"2026-08-16","entries":[{"provider_name":"test","id":"model","aliases":["alias"],"source_url":"https://example.test/model","limits":{"context_window_tokens":10,"max_output_tokens":2},"profile":{"supports_tools":true,"reasoning_efforts":["low"]}}]}
    ;
    const first = try generate(std.testing.allocator, fixture);
    defer std.testing.allocator.free(first);
    const second = try generate(std.testing.allocator, fixture);
    defer std.testing.allocator.free(second);
    try std.testing.expectEqualStrings(first, second);
    try std.testing.expect(std.mem.indexOf(u8, first, ".supports_tools = true") != null);
    try std.testing.expect(std.mem.indexOf(u8, first, ".supports_temperature = false") != null);
    try std.testing.expect(std.mem.indexOf(u8, first, ".reasoning_efforts = model.ModelProfile.ReasoningEffortSet.initMany(&.{.low})") != null);

    try std.testing.expectError(error.InvalidModelCatalogSource, generate(
        std.testing.allocator,
        "{\"version\":2,\"updated_at\":\"2026-08-16\",\"entries\":[]}",
    ));
    try std.testing.expectError(error.InvalidModelCatalogSource, generate(
        std.testing.allocator,
        "{\"version\":1,\"updated_at\":\"bad\",\"entries\":[]}",
    ));
    try std.testing.expectError(error.InvalidModelCatalogSource, generate(
        std.testing.allocator,
        "{\"version\":1,\"updated_at\":\"2026-02-29\",\"entries\":[]}",
    ));
}

test "generator releases every allocation" {
    const fixture =
        \\{"version":1,"updated_at":"2026-08-16","entries":[{"provider_name":"test","id":"model","source_url":"https://example.test/model","profile":{}}]}
    ;
    try std.testing.checkAllAllocationFailures(std.testing.allocator, struct {
        fn exercise(allocator: std.mem.Allocator, source: []const u8) !void {
            const generated = try generate(allocator, source);
            defer allocator.free(generated);
        }
    }.exercise, .{fixture});
}
