        .builtin_tools = model.ModelProfile.BuiltinToolSet.initMany(source.builtin_tools),
        .content_types = model.ModelProfile.ContentTypeSet.initMany(source.content_types),
    };
}

fn writeEntry(writer: *std.Io.Writer, entry: SourceEntry) !void {
    try writer.print(
        "    .{{\n        .provider_name = \"{f}\",\n        .id = \"{f}\",\n",
        .{ std.zig.fmtString(entry.provider_name), std.zig.fmtString(entry.id) },
    );
    try writer.writeAll("        .aliases = &.{");
    if (entry.aliases.len > 1) try writer.writeByte(' ');
    for (entry.aliases, 0..) |alias, index| {
        if (index > 0) try writer.writeAll(", ");
        try writer.print("\"{f}\"", .{std.zig.fmtString(alias)});
    }
    if (entry.aliases.len > 1) try writer.writeByte(' ');
    try writer.writeAll("},\n");
    try writer.print("        .source_url = \"{f}\",\n", .{std.zig.fmtString(entry.source_url)});
    if (entry.deprecation) |deprecation| try writeDeprecation(writer, deprecation);
    try writer.writeAll("        .limits = .{ .context_window_tokens = ");
    try writeOptionalInteger(writer, entry.limits.context_window_tokens);
    try writer.writeAll(", .max_output_tokens = ");
    try writeOptionalInteger(writer, entry.limits.max_output_tokens);
    try writer.writeAll(" },\n");
    try writeProfile(writer, entry.profile);
    try writer.writeAll("    },\n");
}

fn writeDeprecation(writer: *std.Io.Writer, deprecation: catalog.Deprecation) !void {
    try writer.writeAll("        .deprecation = .{\n");
    if (deprecation.since) |value|
        try writer.print("            .since = \"{f}\",\n", .{std.zig.fmtString(value)});
    if (deprecation.sunset) |value|
        try writer.print("            .sunset = \"{f}\",\n", .{std.zig.fmtString(value)});
    if (deprecation.replacement) |value|
        try writer.print("            .replacement = \"{f}\",\n", .{std.zig.fmtString(value)});
    try writer.writeAll("        },\n");
}

fn writeProfile(writer: *std.Io.Writer, profile: SourceProfile) !void {
    try writer.writeAll("        .profile = .{\n");
    inline for (profile_boolean_fields) |field| {
        try writer.print("            .{s} = {},\n", .{ field, @field(profile, field) });
    }
    if (profile.extra_body_kind) |kind|
        try writer.print("            .extra_body_kind = .{s},\n", .{@tagName(kind)});
    try writeEnumSet(writer, "reasoning_efforts", profile.reasoning_efforts);
    try writeEnumSet(writer, "service_tiers", profile.service_tiers);
    try writeEnumSet(writer, "builtin_tools", profile.builtin_tools);
    try writeEnumSet(writer, "content_types", profile.content_types);
    try writer.writeAll("        },\n");
}

